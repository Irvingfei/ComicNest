let current = "en";

/* TOS keeps the desktop language in the parent document's storage. The app is
   framed under the same origin, so those stores are readable; key names differ
   between TOS releases, so every plausible spelling is probed. */
const TOS_KEYS = [
  "tos_language", "tos-lang", "tosLanguage", "tos_lang",
  "langModel", "lang_model",
  "language", "lang", "locale", "ui_language", "i18n_language",
];
const TOS_PARAMS = ["lang", "language", "locale"];

function normalizeTag(value) {
  const tag = String(value === undefined || value === null ? "" : value)
    .trim().toLowerCase().replace(/_/g, "-");
  if (!tag || tag.length > 20 || !/^[a-z]{2,3}(-[a-z0-9]{1,8})*$/.test(tag)) return "";
  return tag;
}

function tagFor(tag) {
  if (!tag) return "";
  if (tag.startsWith("zh")) return /hant|tw|hk|mo/.test(tag) ? "zh-TW" : "zh-CN";
  const short = tag.split("-")[0];
  return STRINGS[short] ? short : "";
}

function ownStore() {
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

function readStore(store) {
  if (!store) return "";
  for (const key of TOS_KEYS) {
    try {
      const tag = normalizeTag(store.getItem(key));
      if (tag) return tag;
    } catch {
      return "";
    }
  }
  try {
    for (let i = 0; i < store.length; i += 1) {
      const key = store.key(i);
      if (!key || key.startsWith("comicnest.") || !/lang|locale/i.test(key)) continue;
      const tag = normalizeTag(store.getItem(key));
      if (tag) return tag;
    }
  } catch {
    /* treat as absent */
  }
  return "";
}

function readCookie() {
  let text = "";
  try {
    text = document.cookie || "";
  } catch {
    return "";
  }
  for (const part of text.split(";")) {
    const cut = part.indexOf("=");
    if (cut < 0 || !/lang|locale/i.test(part.slice(0, cut))) continue;
    let raw = part.slice(cut + 1).trim();
    try {
      raw = decodeURIComponent(raw);
    } catch {
      /* keep the raw value */
    }
    const tag = normalizeTag(raw);
    if (tag) return tag;
  }
  return "";
}

function readParam() {
  let query = "";
  try {
    query = String(window.location.search || "");
  } catch {
    return "";
  }
  for (const name of TOS_PARAMS) {
    const match = new RegExp("[?&]" + name + "=([^&]+)").exec(query);
    if (!match) continue;
    let raw = match[1];
    try {
      raw = decodeURIComponent(raw);
    } catch {
      /* keep the raw value */
    }
    const tag = normalizeTag(raw);
    if (tag) return tag;
  }
  return "";
}

function readParent() {
  let parentWindow = null;
  let parentDoc = null;
  try {
    parentWindow = window.parent && window.parent !== window ? window.parent : null;
    parentDoc = parentWindow ? parentWindow.document : null;
  } catch {
    return "";
  }
  if (!parentDoc) return "";
  try {
    const html = parentDoc.documentElement;
    const tag = normalizeTag(
      html && (html.getAttribute("lang") || html.getAttribute("xml:lang") || html.getAttribute("data-lang"))
    );
    if (tag) return tag;
  } catch {
    /* fall through to the parent's storage */
  }
  try {
    return readStore(parentWindow.localStorage);
  } catch {
    return "";
  }
}

/* Raw TOS tag, whether or not this build has a dictionary for it. */
export function tosLanguage() {
  return readParam() || readStore(ownStore()) || readCookie() || readParent();
}

/* TOS first, then the browser. A TOS language without a dictionary falls back
   to English rather than to the browser's unrelated preference. */
export function deviceLanguage() {
  const tos = tosLanguage();
  if (tos) return tagFor(tos) || "en";
  const candidates = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];
  for (const candidate of candidates) {
    const code = tagFor(normalizeTag(candidate));
    if (code) return code;
  }
  return "en";
}

/* Report TOS language changes made in the desktop (storage event, parent
   document mutation, refocus) so "follow TOS" stays live. */
export function watchSystemLanguage(callback) {
  let last = tosLanguage();
  const check = () => {
    const next = tosLanguage();
    if (next === last) return;
    last = next;
    callback(next);
  };
  try {
    window.addEventListener("storage", (event) => {
      if (!event || !event.key || (/lang|locale/i.test(event.key) && !/^comicnest\./i.test(event.key))) {
        check();
      }
    });
  } catch {
    /* no storage events available */
  }
  try {
    const parentDoc = window.parent && window.parent !== window ? window.parent.document : null;
    if (parentDoc && window.MutationObserver) {
      new window.MutationObserver(check).observe(parentDoc.documentElement, {
        attributes: true,
        attributeFilter: ["lang", "xml:lang", "data-lang"],
      });
    }
  } catch {
    /* not embedded, or the parent is another origin */
  }
  window.addEventListener("focus", check);
  window.setInterval(check, 3000);
}

export function setLanguage(code) {
  current = STRINGS[code] ? code : "en";
  document.documentElement.lang = current;
  return current;
}

export function getLanguage() {
  return current;
}

/* The built-in library keeps a fixed stored name so scans and databases stay
   stable; show it in the reader's language instead. */
export function sourceLabel(name) {
  return name === "ComicNest Library" ? t("source.defaultName") : name;
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let text = table[key];
  if (text === undefined) text = STRINGS.en[key];
  if (text === undefined) return key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split("{" + name + "}").join(String(value));
    }
  }
  return text;
}

export function messageForCode(code, fallback) {
  const numeric = Number(code);
  if (numeric === 1401) return t("error.auth");
  if (numeric === 1402) return t("error.identity");
  if (numeric === 1403) return t("error.forbidden");
  if (numeric === 1404 || numeric === 3101 || numeric === 3102) return t("error.notFound");
  if (numeric === 1415 || numeric === 3103) return t("error.unsupported");
  if (numeric === 3001) return t("error.sourceUnavailable");
  if (numeric === 3201 || numeric === 3202) return t("error.remote");
  return fallback || t("error.generic");
}
